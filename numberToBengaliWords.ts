  if (Math.floor(num / 100) > 0) {
    words += bnNumbers[Math.floor(num / 100)] + " শত ";
    num %= 100;
  }

  // Handle remaining 1-99
  if (num > 0) {
    words += bnNumbers[num];
  }

  // Clean up extra spaces and return
  return words.trim().replace(/\s+/g, " ");
